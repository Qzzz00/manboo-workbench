/**
 * 通话里哪一句该转给**事务官本体**(2026-09-23,「通话里的她 = 本体」)。
 *
 * 今天电话里说话的是工人自己那只小模型:它快(这正是它存在的理由),
 * 但它**看不见记忆、判断不了事项、用不了工作台的工具** —— 于是他问
 * 「上周那个登录页到底谁在做」,她只能凭系统提示里那份快照胡诌。那是 D13 里最坏的一种失真。
 *
 * 所以分两路:
 *   - **闲聊、寒暄、语气、当场就能答的** → 工人自己答(为了快);
 *   - **要判断事项、要读记忆、要用工作台工具的** → 转本体(`POST /butler/item/say`),
 *     拿回它的原话再念。
 *
 * 代价明写:转本体要经 DSH 一个来回,慢的那几秒由垫场语盖(filler.ts 那条白名单)。
 * 判据写成**规则**不交给模型:模型每次分得不一样,而「她到底是凭什么答的」
 * 必须是一件可解释的事。规则判不准的一律**按闲聊走工人**(慢比错好听,但错比慢更糟 ——
 * 这里的取舍是:只有明确认出「这是要查的」才去查,认不出就老实说不知道,由人设那条规矩兜着)。
 */

import { matchSpokenFamily, type SpokenFamily } from './agentName.ts'

/**
 * 这一句归谁答。
 *
 * 2026-10-28(A2,理解中枢):「问事项」「问记忆」那两张词表(`ITEM_WORDS` / `MEMORY_WORDS`)拆了 ——
 * 它们拦在模型前面替它判「这是问,不是办」,10-22 那句「帮我建一个待办…」就是被判成问事项、手上没有建卡的工具。
 * 写板子的那几件工具现在每一回合都在手上(intentTools.ts 的 ALWAYS_TOOLS),是问是办由模型看上下文包定。
 * 只留捎话这一类:它是**硬护栏**(没让发就不许往别人的窗口里打字),不是意图分流。
 */
export type CallRoute =
  /**
   * **给某条会话捎句话**(2026-09-26,卡 BR):「给那个 Claude、现在正在做统筹交接的那个会话窗口,
   * 发个信息问一下:现在进行到什么情况」。走 `wb_relay_to_session` → 工作台 `POST /sessions/relay`,
   * **不需要任何事项**,认会话靠标题 / 家名 / 状态。
   */
  | 'relay'
  /** 工人自己的模型答(带着全部写板子的工具与上下文包)。 */
  | 'chat'

/**
 * 捎话那一类:**送话的动作**(2026-09-26,卡 BR)。
 * 光有这一类词还不算 —— 还得点着一个**对象**(见 {@link RELAY_TARGET_WORDS}):
 * 「告诉他我下午到」是闲聊,「告诉 Claude 那条会话我下午到」是捎话。
 */
const RELAY_SEND_WORDS = [
  '发个信息', '发条信息', '发个消息', '发条消息', '发信息', '发消息', '发一句', '发一条', '发过去', '发给',
  '捎个话', '捎句话', '捎话', '传个话', '传句话', '传话',
  '问一下它', '问一下他', '问问它', '问问他', '告诉它', '告诉他', '跟它说', '跟他说', '给它说', '说一声', '说一句',
  // 2026-09-27(卡 MS):「问问 X」也是捎话(维护者定的第 2 条)。光有这两个词不算 ——
  // 下面那一半还要点着一个对象,所以「问一下现在几点」不会被当成捎话。
  '问问', '问一下',
] as const

/** 捎话那一类:**送给谁**。家名也算 —— 「跟 Claude 说一句」。 */
const RELAY_TARGET_WORDS = [
  '会话', '窗口', '对话', '那条', '那一条', 'claude', 'codex', 'kimi', '豆包', 'muse', 'manus',
] as const

/**
 * 他这一句是**要给某条会话捎话**吗(2026-09-26,卡 BR)。判据写成规则:**送话的动作 + 点着一个对象**,
 * 两样都有才算。少一样就不算 —— 认错了会把他一句闲聊当成要往别人的窗口里打的字。
 */
export function looksLikeRelay(text: string, families?: readonly SpokenFamily[]): boolean {
  const said = text.toLowerCase()
  /**
   * ★ **只读那道门优先**(2026-09-27,卡 LK + 卡 MS 合流)。
   *
   * 他明说别发(「**不要**给他发信息,就看一眼」)、或者整句就是在问状态而**一个送话动词都没有** ——
   * 一律不算捎话。**被否掉的送话动词不算许可**:句子里有「发信息」,可它前面跟着一个「不要」。
   *
   * 判反了的代价是不对称的:少捎一次他再说一遍就行;多捎一次是**往别人的窗口里真打了字**。
   */
  if (NO_SEND_RE.test(said)) return false
  if (looksLikeLookupOnly(text)) return false
  if (!RELAY_SEND_WORDS.some(word => said.includes(word))) return false
  if (RELAY_TARGET_WORDS.some(word => said.includes(word))) return true
  /*
   * ★ 2026-09-27(卡 MS):**名字听错了也得认出这是在点某一家**。
   *
   * 21:17 那一通:「给 minus 发个信息问他国庆节中国法定节日是放几天」——「发个信息」在上面那张表里,
   * 可 `minus` 不在下面那张表里(表里写的是 `manus`),于是整句没被认成捎话,一路走到了
   * 「交给事务官办」:建了一张卡、开了一条 DSH 会话去 grep「minus」,一个字都没发出去。
   * 现在这一半交给读音近似(`agentName.ts`,与登记表同一份名单),写死的词表只当快路。
   */
  return matchSpokenFamily(text, families).kind !== 'none'
}

/**
 * **「看一眼」那一类:只看,不许送**(2026-09-27,卡 LK)。
 *
 * 现场(维护者 21:2x):「你告诉我现在 Codex 现在是什么状态?」→ 事务官去**给 Codex 捎话**;
 * 他明说「不要给他发信息,就看一眼」→ 还是答旧事项。**没让发就发了**是这一通里最伤的一条。
 *
 * 所以这道门写成代码,不靠模型自觉:他这一句里有「问状态」的意思、又**没有一个明确的送话动词**
 * ({@link RELAY_SEND_WORDS} 里那些「发给 / 跟他说 / 捎句话 / 告诉他」),就一律不许调捎话那件工具。
 *
 * 判反了的代价是不对称的:少捎一次他再说一遍就行;多捎一次是**往别人的窗口里真打了字**。
 */
const LOOKUP_WORDS = [
  '看一眼', '看看', '瞅一眼', '瞄一眼', '去看', '查一下状态', '什么状态', '啥状态', '状态怎么样',
  '在干什么', '在干嘛', '在做什么', '在忙什么', '到哪了', '到哪一步', '进行到', '跑到哪',
  '跑完了没', '跑完没', '还在跑吗', '还在跑没', '停了没', '停了吗', '有没有动静', '有动静吗',
  '现在怎么样', '怎么样了', '多久了',
] as const

/**
 * 他**明说别发**的那几种说法(2026-09-27,卡 LK)。维护者那一通里的原话就是
 * 「**不要给他发信息**,就看一眼」——句子里有「发信息」,可它前面跟着一个「不要」。
 * 光按 {@link RELAY_SEND_WORDS} 命中就放行,等于把他这句禁令当成了许可。
 *
 * 只认这几个前缀:「不要 / 不用 / 别 / 不许 / 先不」接着一个送话的动词。
 * 认得出就当**一个送话动词都没有**(他在禁,不在派)。
 */
const NO_SEND_RE = /(不要|不用|不需要|别|不许|先不)\s*(给[^,,。;;]{0,6})?(发|捎|传|问|告诉|跟.{0,3}说|说一声)/u

export function looksLikeLookupOnly(text: string): boolean {
  const said = text.toLowerCase()
  if (!LOOKUP_WORDS.some(word => said.includes(word))) return false
  if (NO_SEND_RE.test(said)) return true
  return !RELAY_SEND_WORDS.some(word => said.includes(word))
}

/**
 * **他这一句是「打断再发」,还是只是「补一句」**(2026-09-28,卡 WR)。
 *
 * 维护者点的第三个场景:「给工作中的会话发信息,**并且打断发送新信息**」。两种意图差得远:
 * - 「补一句」:话排进那条会话,它跑完自己看见 —— 它照旧干它正在干的活;
 * - 「打断再发」:**先按那家的停止键**,停下了才把这句话送进去 —— 它正在干的那件事就这么废了。
 *
 * 所以这道门也写成代码、不靠模型自觉:他说「打断它 / 先停下 / 别做了改成…」才算打断。
 * **认不准一律按「补一句」** —— 多送一句话是他自己要送的那句,无端按一下停止键是我们把他的活废了。
 *
 * 这一份与插件那一侧 `server/relayMove.ts` 的 `looksLikeInterrupt` 同一个口径
 * (两边各有用例钉着;`channel-worker` 不 import 插件的代码,所以是两份写法、一份口径)。
 */
const INTERRUPT_WORDS = [
  '打断', '中断', '先停', '停下', '停一下', '先别做', '别做了', '不要做了', '不用做了',
  '停止', '叫停', '喊停', '终止', '别弄了', '取消掉', '先取消',
] as const

export function looksLikeInterrupt(text: string): boolean {
  const flat = text.replace(/[\s　]+/g, '')
  if (flat === '') return false
  return INTERRUPT_WORDS.some(word => flat.includes(word))
}

/**
 * 这一句该走哪条路:认得出是捎话就是 `relay`,别的一律 `chat`(交给模型)。
 */
export function classifyCallTurn(text: string): CallRoute {
  const trimmed = text.trim()
  if (trimmed === '') return 'chat'
  return looksLikeRelay(trimmed) ? 'relay' : 'chat'
}

/** 转本体的时候附在他那句话前面的上下文一行。让本体知道这是电话里问的,答案要短。 */
export function butlerAskPrefix(route: 'ask' | 'relay'): string {
  /**
   * 捎话那一条(卡 BR):本体收到的是「他要你把这句话送进某条会话」,不是「回答他这个问题」。
   * **不许**回「这归哪件事」——那条路不要事项(技能「捎话给正在跑的会话」写着怎么走)。
   */
  if (route === 'relay') {
    return '【电话里他要你给某条会话捎句话】下面这句是他在电话里说的。按技能「捎话给正在跑的会话」办:'
      + '调 POST /sessions/relay,把他点名那一句填 who、他要捎的话原样填 text(一个字都别改写)。'
      + '认出几条就把候选念给他选,认不出就问他是哪一条。'
      + '**不要**问他「这归哪件事」——捎话不需要事项。捎到了说捎到了,捎不到说清哪一步没成。'
      + '回话用两三句人话,不要列清单、不要写 Markdown、不要念 id 与路径(他在用耳朵听)。\n'
  }
  return '【电话里他问的】下面这句是他在电话里问的,用两三句人话回答,'
    + '不要列清单、不要写 Markdown、不要念 id 与路径(他在用耳朵听)。答不上来就说答不上来。\n'
}
