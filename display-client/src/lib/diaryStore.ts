import { markLocalChanged } from './syncEngine.ts';

export type DiaryComment = {
  id: string;
  authorId: string;
  authorName: string;
  text: string;
  time: number;
};

export type DiaryEntry = {
  id: string;
  authorId: string;
  authorName: string;
  text: string;
  image?: string;
  emotion?: string;
  time: number;
  likes: string[];
  comments: DiaryComment[];
};

type DiaryStore = Record<string, DiaryEntry[]>;

const DIARY_KEY = 'llm-live2d:diary';
const LAST_GEN_KEY = 'llm-live2d:diary-last-gen';

