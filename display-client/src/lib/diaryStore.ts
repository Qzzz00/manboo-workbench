export function loadDiary(): DiaryStore {
  try {
    seedIfEmpty();
    const raw = localStorage.getItem(DIARY_KEY);
    if (!raw) return {};
    const parsed = JSON.parse(raw) as DiaryStore;
    return parsed;
  } catch (e) {
    console.error('[diary] loadDiary error:', e);
    return {};
  }
}

function saveDiary(store: DiaryStore) {
  localStorage.setItem(DIARY_KEY, JSON.stringify(store));
  markLocalChanged('diary');
}

const THIRTY_DAYS = 30 * 24 * 60 * 60 * 1000;

function filterExpired(entries: DiaryEntry[]): DiaryEntry[] {
  const cutoff = Date.now() - THIRTY_DAYS;
  return entries.filter((e) => e.time > cutoff);
}

export function getEntries(authorId: string): DiaryEntry[] {
  const store = loadDiary();
  return filterExpired(store[authorId] || []).sort((a, b) => b.time - a.time);
}

export function getAllEntries(): DiaryEntry[] {
  const store = loadDiary();
  const all: DiaryEntry[] = [];
  for (const key of Object.keys(store)) {
    all.push(...filterExpired(store[key] || []));
  }
  return all.sort((a, b) => b.time - a.time);
}

export function getDiaryEntryCount(avatarId?: string): number {
  if (avatarId) return getEntries(avatarId).length;
  return getAllEntries().length;
}

export function addEntry(entry: DiaryEntry) {
  const store = loadDiary();
  if (!store[entry.authorId]) store[entry.authorId] = [];
  store[entry.authorId].push(entry);
  saveDiary(store);
}

export function toggleLike(entryId: string, userId: string): boolean {
  const store = loadDiary();
  for (const key of Object.keys(store)) {
    const entry = store[key].find((e) => e.id === entryId);
    if (entry) {
      const idx = entry.likes.indexOf(userId);
      if (idx >= 0) entry.likes.splice(idx, 1);
      else entry.likes.push(userId);
      saveDiary(store);
      return idx < 0; // true = liked, false = unliked
    }
  }
  return false;
}

export function addComment(entryId: string, comment: DiaryComment) {
  const store = loadDiary();
  for (const key of Object.keys(store)) {
    const entry = store[key].find((e) => e.id === entryId);
    if (entry) {
      entry.comments.push(comment);
      saveDiary(store);
      return;
    }
  }
}

export function getLastGenTime(authorId: string): number {
  try {
    const raw = localStorage.getItem(LAST_GEN_KEY);
    if (!raw) return 0;
    const map = JSON.parse(raw) as Record<string, number>;
    return map[authorId] || 0;
  } catch { return 0; }
}

export function setLastGenTime(authorId: string) {
  try {
    const raw = localStorage.getItem(LAST_GEN_KEY);
    const map = raw ? JSON.parse(raw) as Record<string, number> : {};
    map[authorId] = Date.now();
    localStorage.setItem(LAST_GEN_KEY, JSON.stringify(map));
    markLocalChanged('diary');
  } catch { /* ignore */ }
}

export function getUserUnreadCount(): number {
  const store = loadDiary();
  // entries not used currently
  // Count entries generated by characters (not user) since last view
  let count = 0;
  for (const key of Object.keys(store)) {
    if (key === '_user') continue;
    count += (store[key] || []).length;
  }
  return count;
}
