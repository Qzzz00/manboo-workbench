/** WMO weather code → 中文 + emoji（屏保直连 open-meteo 时用；与后端 weather.cjs 对齐）。 */
export function weatherCodeToCondition(code: number): { zh: string; icon: string } {
  const map: Record<number, [string, string]> = {
    0: ['晴', '☀️'],
    1: ['多云间晴', '🌤️'],
    2: ['多云', '⛅'],
    3: ['阴', '☁️'],
    45: ['雾', '🌫️'],
    48: ['雾凇', '🌫️'],
    51: ['小毛毛雨', '🌦️'],
    53: ['毛毛雨', '🌦️'],
    55: ['大毛毛雨', '🌦️'],
    56: ['冻毛毛雨', '🌧️'],
    57: ['冻毛毛雨', '🌧️'],
    61: ['小雨', '🌧️'],
    63: ['中雨', '🌧️'],
    65: ['大雨', '🌧️'],
    66: ['冻雨', '🌧️'],
    67: ['冻雨', '🌧️'],
    71: ['小雪', '🌨️'],
    73: ['中雪', '🌨️'],
    75: ['大雪', '❄️'],
    77: ['雪粒', '🌨️'],
    80: ['阵雨', '🌦️'],
    81: ['阵雨', '🌦️'],
    82: ['强阵雨', '⛈️'],
    85: ['阵雪', '🌨️'],
    86: ['强阵雪', '❄️'],
    95: ['雷阵雨', '⛈️'],
    96: ['雷阵雨伴冰雹', '⛈️'],
    99: ['强雷阵雨伴冰雹', '⛈️'],
  };
  const hit = map[Number(code)] || ['未知', '🌡️'];
  return { zh: hit[0], icon: hit[1] };
}
