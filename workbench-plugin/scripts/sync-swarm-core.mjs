/** Deterministic prototype → static ESM. Validate every staged artifact before replacing any output. */
import { readFile, mkdir, mkdtemp, writeFile, rename, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const here = fileURLToPath(new URL('.', import.meta.url))
const source = resolve(here, '../../docs/prototypes/swarm-v4')
const destination = resolve(here, '../src/client/swarm')
// 2026-09-16:同一份核心也生成到手机端(butler-app),外观配置两端共用、渲染一字不差;core.d.ts 随行拷过去。
const mirrors = [resolve(here, '../../butler-app/src/swarm'), resolve(here, '../../display-client/src/swarm')]
const names = ['tuning.js', 'motion.js', 'icons.js', 'svg-import.js', 'icon-library.js', 'icon-picker.js', 'cloud.js', 'hole-light.js', 'renderer.js']
const hashes = {}, chunks = []
for (const name of names) {
  const original = await readFile(join(source, name), 'utf8')
  hashes[name] = createHash('sha256').update(original).digest('hex')
  let code = original
  if (name === 'icon-picker.js') code = code.slice(0, code.indexOf('class IconPicker'))
  // Seed sampling is scoped to an explicitly supplied SVG host, never global DOM.
  if (name === 'icons.js') code = code.replace('sampleGlyphs()', 'sampleGlyphs(root)').replace("document.querySelectorAll('svg[data-glyph]')", "root.querySelectorAll('svg[data-glyph]')")
  chunks.push(`// SOURCE: docs/prototypes/swarm-v4/${name}\n${code}`)
}
const exports = ['TUNING_FIELDS', 'TUNING_DEFAULTS', 'TUNING_STORAGE_KEY', 'normalizeTuning', 'parseTuningPreset', 'readTuningPreset', 'SwarmV4', 'SwarmRenderer', 'sampleGlyphs', 'sanitizeParticleSVG', 'sampleImportedSVG', 'listBuiltinIcons', 'getBuiltinIcon', 'BuiltinGlyphCache', 'alignSquare', 'cloudResolutionFor', 'LightCloud']
const license = await readFile(join(source, 'THIRD_PARTY_LICENSES.txt'), 'utf8')
if (!license.includes('MIT') || !license.includes('Kuna')) throw new Error('Missing upstream license')
const core = `// GENERATED by scripts/sync-swarm-core.mjs. Do not edit.\n/*!\n${license}\n*/\n${chunks.join('\n')}\nexport { ${exports.join(', ')} };\n`
if (/\beval\s*\(|new\s+Function\b|class IconPicker|class TaskScene|4177|<iframe/i.test(core)) throw new Error('Unexpected runtime/demo dependency')
const artifacts = { 'core.js': core, 'source-manifest.json': JSON.stringify({ source: 'docs/prototypes/swarm-v4', files: hashes }, null, 2) + '\n', 'THIRD_PARTY_LICENSES.txt': license }
await mkdir(destination, { recursive: true })
const stage = await mkdtemp(join(tmpdir(), 'workbench-swarm-staging-'))
for (const [name, body] of Object.entries(artifacts)) await writeFile(join(stage, name), body)
execFileSync(process.execPath, ['--check', join(stage, 'core.js')])
const { TUNING_FIELDS, listBuiltinIcons } = await import(new URL(`file://${join(stage, 'core.js')}`))
if (TUNING_FIELDS.length !== 24 || listBuiltinIcons().length !== 120) throw new Error('Prototype catalog/tuning contract changed')
const typings = await readFile(join(destination, 'core.d.ts'), 'utf8')
if (process.argv.includes('--check')) {
  for (const [name, body] of Object.entries(artifacts)) if (await readFile(join(destination, name), 'utf8') !== body) throw new Error(`Out of sync: ${name}`)
  for (const mirror of mirrors) {
    for (const [name, body] of Object.entries(artifacts)) if (await readFile(join(mirror, name), 'utf8') !== body) throw new Error(`Out of sync: ${mirror}/${name}`)
    if (await readFile(join(mirror, 'core.d.ts'), 'utf8') !== typings) throw new Error(`Out of sync: ${mirror}/core.d.ts`)
  }
} else {
  for (const mirror of mirrors) {
    await mkdir(mirror, { recursive: true })
    for (const [name, body] of Object.entries(artifacts)) await writeFile(join(mirror, name), body)
    await writeFile(join(mirror, 'core.d.ts'), typings)
  }
  for (const name of Object.keys(artifacts)) await rename(join(stage, name), join(destination, name))
}
// Only our validated mkdtemp staging directory is removed, after every file passed.
await rm(stage, { recursive: true })
console.log(`Swarm source ${process.argv.includes('--check') ? 'verified' : 'synchronized'}: 9 sources, 24 fields, 120 lazy icons, ${1 + mirrors.length} targets`)
