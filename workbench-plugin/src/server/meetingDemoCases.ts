/**
 * 三场演示用的会(2026-10-13,卡「会议页不再空着」)。维护者原话:
 * 「会议里还是空的,我想的是会议里要有一些方便演示的历史会议案例,一样按照会前会中会后三个来看」。
 *
 * ## 为什么是常量,不是仓库里的文件
 *
 * 演示机上**没有源码仓库**:`docs/演示/` 里那份样例她拿不到。所以三场的材料编进插件产物
 * (同 `bundledSkills` 的做法),一键就能放进去。
 *
 * ## 三场都是虚构的
 *
 * 不是任何真实公司、真实会议、真实人物;花名(小满 / 阿山 / 品牌方)是编的;**一处凭据都没有**。
 * 转写照 `转写.md` 的样子写(方括号里是从会议开始算起的时间),**没有说话人分离**,所以不标谁说的。
 *
 * ## 每一场里都埋了什么(给演示讲的那几句)
 *
 * - **会前**:`said` 是她登记那一句(走 `/meeting/plan` 的真路);`answers` 是五问各答什么
 *   (走 `/meeting/answer`)。认得出的那几问**不在这里**答 —— 词表从 `said` 里认出来就不问了
 *   (「跟品牌方」→ 外部、「争取敲定…」→ 要定什么),所以 seed 是**照它此刻问的那一问**答,不是按固定顺序灌。
 * - **会中**:转写里的时间戳 → 一条时间线(`timelineOf`)。「记一下」那种现场记号**现在没有**,
 *   所以这三场里一个都没有 —— 界面上如实不显示,不编。
 * - **会后**:`transcript` 走 `/meeting/import` 出纪要。`nextSteps` 是这一场转写里**本来就有**的行动项,
 *   用例据此钉住:人名与期限的字必须在转写里出现过,否则《会议纪要生成规则》第 9 条那道程序闸会把整条丢掉
 *   (`saidInTranscript`)—— 样例一改、钉子当场红。
 */
import type { MeetingPrepQuestionId } from '../protocol.ts'

/** 这一场转写里本来就有的一条行动项。`who` 缺席 = 会上没点名(那条正是用来验「不许自己补一个负责人」的)。 */
export interface MeetingDemoNextStep {
  who?: string
  due: string
}

export interface MeetingDemoCase {
  /** 稳定的号(用例、日志、彩排页里认它;不进界面)。 */
  key: string
  /**
   * 这一场该叫什么。**不是另一条起名的路** —— 标题是 `draftMeetingPlan` 从 `said` 里切出来的那一截,
   * 这一格只是把它写下来给「重复点不重复放」那道闸比对(用例钉着两者一致)。
   */
  title: string
  /** 她登记那一句(走 `/meeting/plan`)。 */
  said: string
  /** 五问各答什么(走 `/meeting/answer`;词表已经认出来的那几问不会被问到)。 */
  answers: Partial<Record<MeetingPrepQuestionId, string>>
  /** 转写正文(带时间戳,照 `转写.md` 的样子)。 */
  transcript: string
  /** 这一场演示讲什么(seed 的回话与彩排页用同一句)。 */
  blurb: string
  /** 转写里本来就有的行动项(用例钉住第 9 条那道闸不会把它们丢掉)。 */
  nextSteps: readonly MeetingDemoNextStep[]
}

