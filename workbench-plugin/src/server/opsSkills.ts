export interface OpsSkillDef {
  /** 文件名去掉 `.md`,**同时**就是 AGENTS.md 里那个标记段的名字。 */
  name: string
  /** 给人看的一句话(设置里那颗按钮底下列的就是这一行)。 */
  summary: string
  /**
   * 这一段对应她工作里的**哪个环节**,以及她可能有什么偏好(2026-10-02,
   * 卡「提示词页改成她的偏好页」)。
   *
   * 带了这一格的技能,设置里「你各个环节的偏好」那一栏就多一行:她写的几句短话由本体
   * 在写 AGENTS.md 那一刻接在这一段正文末尾(`promptOverrides.withPromptPrefs`)。
   *
   * ★ **环节名与例子写在这儿、不写在界面里**:界面上写一份就等于第二份清单 ——
   * 加一条技能、换一个模板,那份清单迟早漏(同「段名是扫出来的」那条理由)。
   * 当前模板下有哪几个环节 = `opsSkillsForTemplate(模板)` 里带这一格的那几条。
   *
   * 缺席 = 这一段不是她会有偏好的"做事环节"(口径类的「运营-总纲」、
   * 工具类的「用说话改布局」),那一栏里不出现它。
   */
  stage?: {
    /** 人话环节名(「选题」「写稿」「标题与封面」)。她在页面上看到的就是这一个词。 */
    title: string
    /**
     * 一句人话:这个环节它替她干什么。
     *
     * ★ **不复用 `summary`**:那一行是给维护者看的(里面有接口路径这种东西),
     * 而这一页上**一个接口、一条路径都不许出现**(用例 `prompts-her-page` 盯着)。
     */
    note: string
    /** 一个例子:这个环节她可能会说的一句偏好。 */
    example: string
  }
  /**
   * 这个技能固定落哪几个文件(相对工作目录)。`<账号名>` / `<选题名>` 是占位,不是真路径,
   * **占位写法与技能文件里逐字一致** —— 下面那条用例是直接 `toContain` 的,两头差一个字就红。
   *
   * 写在这里不是为了给代码用,是为了**用例能对**:技能文件里写的产物路径与这一份
   * 对不上的时候,当场红 —— 两处各写一份路径,改一处忘另一处是迟早的事。
   *
   * 选题类的那几条**不许在这里敲文件名**,走 `topicArtifact(段)`(见文件头)。
   */
  artifacts: readonly string[]
}

