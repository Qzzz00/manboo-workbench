/**
 * 写进 AGENTS.md 的**索引一段**(2026-10-02,卡「事务官为什么要跑这么多步」)。
 *
 * ## 为什么不再把正文整摊写进去
 *
 * `~/.dsh/AGENTS.md` 每开一条会话都整摊注进第一轮上下文(DSH 的 `agent-instructions`)。
 * 量过维护者那台:9 段、**27239 字**、149 处接口说明;Air 上运营模板还多十段。
 * 而**一件事最多用得上一条**:「来来来。」那一通用得上 0 条,照样先读了 18736 字。
 * 10-02 那张「她的偏好页」把这摊从**她眼前**收起来了(页底只读);这一段把同一条做在
 * **机器那一侧** —— 段里只留「它是干什么的 + 正文在哪」,要用那一条才去读那一份。
 *
 * 索引里**不留接口路径**:接口在正文里。段里留一行 `POST /x`,它就会照着那一行直接动手,
 * 而正文里那几条「什么不许做」没读到。
 */
export function opsSkillIndexEntry(skill: OpsSkillDef, bodyFile: string): string {
  return [
    `# 技能:${skill.name}`,
    '',
    skill.summary,
    '',
    `这一条的正文(怎么做、什么不许做、要调哪个口)在 ${bodyFile} —— 这一句话属于这一条时整段读那一份;**不属于这一条就别读**。`,
  ].join('\n')
}

export function opsSkillBody(text: string): string {
  const lines = text.replace(/\r\n/g, '\n').split('\n')
  const head = lines.findIndex(line => line.startsWith('# '))
  if (head === -1) return text.trim()
  let i = head + 1
  while (i < lines.length && lines[i]?.trim() === '') i += 1
  if (lines[i]?.startsWith('>') !== true) return lines.join('\n').trim()
  let end = i
  while (end < lines.length && lines[end]?.startsWith('>') === true) end += 1
  while (end < lines.length && lines[end]?.trim() === '') end += 1
  return [...lines.slice(0, head + 1), '', ...lines.slice(end)].join('\n').trim()
}
