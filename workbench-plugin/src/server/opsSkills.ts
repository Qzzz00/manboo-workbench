/**
 * 「现在到底接上了没有」(2026-09-22,卡 ①)。
 *
 * 判据只有一条:**AGENTS.md 里有没有那一段的开始标记**。不比内容、不比新旧 ——
 * 内容是不是最新那一版由「重新接上」那颗按钮负责(它是幂等的,点一下就对齐了),
 * 这里只回答界面与体检页问的那一句:该在的几段在不在、不该在的几段还剩没剩。
 *
 * 为什么连 `stray`(不该在却还在)也要数:切回做产品模板时如果摘漏了一段,现象是
 * 事务官在做产品模板下还惦记着建 `选题/` 目录 —— 那正是"切了没生效"最难查的一种。
 * 有了这一格,体检页会直说「还剩 n 段该摘没摘」,而不是笼统一句"没接上"。
 */
export interface OpsSkillsAttachState {
  /** 这个模板下**该在**的段名(按写入顺序)。 */
  expected: readonly string[]
  /** 该在、而且**真的在**的。 */
  attached: readonly string[]
  /** 该在、却**不在**的。 */
  absent: readonly string[]
  /** 不该在、却**还在**的(上一次切模板没摘干净)。 */
  stray: readonly string[]
  /** 该在的都在、不该在的都没有。 */
  ok: boolean
}

export function opsSkillsAttachState(text: string | undefined, templateId: string | undefined): OpsSkillsAttachState {
  const body = text ?? ''
  const has = (name: string): boolean => body.includes(markers(name).open)
  const expected = opsSkillsForTemplate(templateId).map(skill => skill.name)
  const attached = expected.filter(has)
  const absent = expected.filter(name => !has(name))
  const stray = ALL_SKILL_NAMES.filter(name => !expected.includes(name) && has(name))
  return { expected, attached, absent, stray, ok: absent.length === 0 && stray.length === 0 }
}

