/**
 * 做完的会话要看得见,气泡要对(2026-09-26,卡 V 补)。
 *
 * 0.4.4 装上之后维护者截图:Claude 标签上是「**1 白 + 1 橙**」,他说**「现在应该是 3 完成 1 进行中」**。
 * 他桌面里 `ben-dsh-workbench` 下那四条会话:
 *
 * | 会话 | 桌面 App 里 | pid 文件 | 会话文件最后一条 | 原来 /state 里 |
 * |---|---|---|---|---|
 * | `Desktop-workbench 统筹交接`(`d9991aac`) | 在跑 | `busy` | `assistant`(工具调用) | running ✓ |
 * | `修 profile 补丁里 cookie 那一行的 id 写错`(`d4ac442e`) | 做完了(蓝点) | `idle` | `assistant` end_turn → `system` | **waiting / idle_prompt**(橙) ✗ |
 * | `Fix flaky wiki-view viewBox transition test`(`6302f07d`) | 做完了(蓝点) | `idle` | `system`(stop_hook_summary) | **根本不在列表里** ✗ |
 * | `让「到上限了」那一问也跨过重启`(`ff8b7326`) | 做完了(蓝点) | `idle` | `system`(stop_hook_summary) | **根本不在列表里** ✗ |
 *
 * 下面的记录片段**照这四份真文件的形状抄**(只留形状,内容全换掉 —— 不存他的原文)。
 *
 * 三处根因,一条一条钉:
 * 1. 最后一条是 `system`(Claude 结束后写的系统记录)、或者是**结束之后那几条不是他说的话的 `user` 记录**
 *    (`isMeta` 的 caveat、斜杠命令展开、命令输出)→ 都要按**最后一条 assistant** 算结果,不能判成「他刚说完话」;
 * 2. 「第一次见到就说完了 → 不回放」把三条做完的整条藏掉了 —— 现在窗口内的一律报,做完的进蓝点那档;
 * 3. 按内容判出来的「在等你」(卡 T)**不改运行状态** —— 说完了顺口问一句,在「几条在跑几条做完」里就是做完了。
 */
import { describe, expect, it } from 'vitest'
import type { SessionView } from '../src/protocol.ts'
import { markOfTail } from '../src/server/claudeSessionRecover.ts'
import { digestClaude } from '../src/server/sessionDigest.ts'
import { judgeSessionOutcome } from '../src/server/sessionOutcome.ts'
import { overlayWaiting, type WaitVerdict } from '../src/server/waitingForYou.ts'

const NOW_MS = Date.parse('2026-09-26T05:21:00.000Z')
const line = (row: unknown): string => JSON.stringify(row)

// ───────────────────── 四份真文件的形状 ─────────────────────

const assistantEnd = (at: string, text: string) =>
  line({ type: 'assistant', message: { role: 'assistant', stop_reason: 'end_turn', content: [{ type: 'text', text }] }, entrypoint: 'claude-desktop', cwd: '/Users/example/x', timestamp: at })

/** Claude 一轮结束后写的那条系统记录(钩子摘要)。**不是**「还在干活」。 */
const stopHook = (at: string) =>
  line({ type: 'system', subtype: 'stop_hook_summary', hookCount: 1, hookErrors: [], preventedContinuation: false, hasOutput: false, timestamp: at })

/** 结束之后那几条记账记录(真机 `6302f07d` / `ff8b7326` 的尾巴就是这几条)。 */
const bookkeeping = (at: string) => [
  line({ type: 'last-prompt', lastPrompt: '接着做', leafUuid: 'u1' }),
  line({ type: 'custom-title', customTitle: '让「到上限了」那一问也跨过重启' }),
  line({ type: 'agent-name', agentName: 'claude' }),
  line({ type: 'atis-latch', atis: '' }),
  stopHook(at),
].join('\n')

/** 结束之后那几条**不是他说的话**的 `user` 记录(真机 `b75d1d3e` 的尾巴)。 */
const afterTurnNoise = [
  line({ type: 'user', isMeta: true, message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running …</local-command-caveat>' }, cwd: '/Users/example/x' }),
  line({ type: 'user', message: { role: 'user', content: '<command-name>/model</command-name>\n<command-message>model</command-message>' }, cwd: '/Users/example/x' }),
  line({ type: 'user', message: { role: 'user', content: '<local-command-stdout>Set model to `claude-opus-5`</local-command-stdout>' }, cwd: '/Users/example/x' }),
  line({ type: 'last-prompt', lastPrompt: '接着做', leafUuid: 'u2' }),
  line({ type: 'cost-state', totalCostUSD: 1.5, startTime: '2026-09-26T03:00:00.000Z' }),
].join('\n')

/** ① 在跑的那条(统筹):最后一条是工具调用。 */
const RUNNING = [
  line({ type: 'user', turnOrigin: 'human', message: { role: 'user', content: [{ type: 'text', text: '接着做下一张卡' }] }, entrypoint: 'claude-desktop', cwd: '/Users/example/x', timestamp: '2026-09-26T05:18:00.000Z' }),
  line({ type: 'assistant', message: { role: 'assistant', stop_reason: 'tool_use', content: [{ type: 'tool_use', name: 'Edit', input: { file_path: '/Users/example/x/a.ts' } }] }, entrypoint: 'claude-desktop', cwd: '/Users/example/x', timestamp: '2026-09-26T05:19:00.000Z' }),
].join('\n')

/** ② 做完了、最后一条是 assistant + system(真机 `d4ac442e`)。 */
const DONE_SYSTEM_LAST = [
  line({ type: 'user', turnOrigin: 'human', message: { role: 'user', content: [{ type: 'text', text: '把那一行 id 修好' }] }, entrypoint: 'claude-desktop', cwd: '/Users/example/x', timestamp: '2026-09-26T04:37:00.000Z' }),
  assistantEnd('2026-09-26T04:39:00.000Z', '修好了。留一条待拍板:已装机器上新签发的才是 3650 天,要不要提示他重新登一次?'),
  stopHook('2026-09-26T04:39:01.000Z'),
].join('\n')

/** ③ 做完了、最后一条是 system,而且前面隔着一串记账记录(真机 `6302f07d` / `ff8b7326`)。 */
const DONE_BOOKKEEPING_LAST = [
  line({ type: 'user', turnOrigin: 'human', message: { role: 'user', content: [{ type: 'text', text: '把那条假红的用例修稳' }] }, entrypoint: 'claude-desktop', cwd: '/Users/example/x', timestamp: '2026-09-26T04:25:00.000Z' }),
  assistantEnd('2026-09-26T04:27:00.000Z', '修稳了,单跑与全量都绿。'),
  bookkeeping('2026-09-26T04:27:30.000Z'),
].join('\n')

/** ④ 做完了、结束之后追了几条不是他说的话的 user 记录(真机 `b75d1d3e`)。 */
const DONE_NOISE_LAST = [
  line({ type: 'user', turnOrigin: 'human', message: { role: 'user', content: [{ type: 'text', text: '把白名单那一条加上' }] }, entrypoint: 'claude-desktop', cwd: '/Users/example/x', timestamp: '2026-09-26T04:10:00.000Z' }),
  assistantEnd('2026-09-26T04:12:00.000Z', '做完了,三处改动都在新分支上。'),
  stopHook('2026-09-26T04:12:01.000Z'),
  afterTurnNoise,
].join('\n')

describe('★① 最后一条不是 assistant,也要按最后一条 assistant 算结果', () => {
  it('最后一条是 `system`(结束后的系统记录)→ 说完了,不是「判不出」也不是「在干活」', () => {
    expect(markOfTail(DONE_SYSTEM_LAST).mark).toBe('ended')
    expect(digestClaude({ head: DONE_SYSTEM_LAST, tail: DONE_SYSTEM_LAST }).mark).toBe('ended')
  })

  it('最后一条是 `system`、前面还隔着一串记账记录 → 一样是说完了', () => {
    expect(markOfTail(DONE_BOOKKEEPING_LAST).mark).toBe('ended')
    expect(digestClaude({ head: DONE_BOOKKEEPING_LAST, tail: DONE_BOOKKEEPING_LAST }).mark).toBe('ended')
  })

  /**
   * ★★这一条是 09-26 抓出来的真 bug:Claude 在最终回答**之后**还会追几条 `user` 记录
   * (`isMeta` 的 caveat、`/model` 这类斜杠命令的展开、命令的输出)。老读法把它们当成
   * 「他刚说完话、它还没开口」→ `asked`,再配上「写它的进程已经没了」就成了**中断**。
   */
  it('★★结束之后那几条不是他说的话的 `user` 记录 → 还是说完了,不许判成「他刚说完话」', () => {
    expect(markOfTail(DONE_NOISE_LAST).mark).toBe('ended')
    expect(digestClaude({ head: DONE_NOISE_LAST, tail: DONE_NOISE_LAST }).mark).toBe('ended')
  })

  it('两条路(只读尾巴 / 读 digest)对同一份文件永远同一个结论', () => {
    for (const text of [RUNNING, DONE_SYSTEM_LAST, DONE_BOOKKEEPING_LAST, DONE_NOISE_LAST]) {
      expect(digestClaude({ head: text, tail: text }).mark).toBe(markOfTail(text).mark)
    }
  })

  it('他真说了一句、它还没开口 → 照旧是 asked(上面那几条不许把这一档也压掉)', () => {
    const asked = [
      assistantEnd('2026-09-26T04:00:00.000Z', '好了'),
      line({ type: 'user', turnOrigin: 'human', message: { role: 'user', content: [{ type: 'text', text: '再帮我看一处' }] }, cwd: '/Users/example/x', timestamp: '2026-09-26T04:01:00.000Z' }),
    ].join('\n')
    expect(markOfTail(asked).mark).toBe('asked')
  })
})

describe('★② 四条会话判出来:1 在跑 + 3 做完', () => {
  /** pid 文件里那四条(桌面 App 都还开着,三条 `idle`、一条 `busy`)。 */
  const cases = [
    { id: 'd9991aac', text: RUNNING, live: 'busy' as const, want: 'running' as const },
    { id: 'd4ac442e', text: DONE_SYSTEM_LAST, live: 'idle' as const, want: 'done' as const },
    { id: '6302f07d', text: DONE_BOOKKEEPING_LAST, live: 'idle' as const, want: 'done' as const },
    { id: 'ff8b7326', text: DONE_NOISE_LAST, live: 'idle' as const, want: 'done' as const },
  ]

  it('逐条判:一条 running、三条 done', () => {
    for (const one of cases) {
      const digest = digestClaude({ head: one.text, tail: one.text })
      const outcome = judgeSessionOutcome({
        ...(digest.mark === undefined ? {} : { mark: digest.mark }),
        writerAlive: true,
        writerBusy: one.live === 'busy',
        ...(digest.last_at === undefined ? {} : { lastAtMs: Date.parse(digest.last_at) }),
        nowMs: NOW_MS,
      })
      expect(outcome?.status, one.id).toBe(one.want)
    }
    expect(cases.filter(one => one.want === 'running')).toHaveLength(1)
    expect(cases.filter(one => one.want === 'done')).toHaveLength(3)
  })

  it('★进程说 idle 就是做完了 —— 不是「待确认」', () => {
    const digest = digestClaude({ head: DONE_SYSTEM_LAST, tail: DONE_SYSTEM_LAST })
    const outcome = judgeSessionOutcome({ mark: digest.mark!, writerAlive: true, writerBusy: false, nowMs: NOW_MS })
    expect(outcome?.status).toBe('done')
    expect(outcome?.status).not.toBe('waiting')
  })
})

// ───────────────────── ③ 内容上的「在等你」不改运行状态 ─────────────────────

const view = (more: Partial<SessionView> & Pick<SessionView, 'session_id' | 'status'>): SessionView => ({
  agent: 'claude', project: '工作台', elapsed_sec: 600, unread: true, updated_at: '2026-09-26T04:39:00.000Z', ...more,
} as SessionView)

const verdict = (by: WaitVerdict['by'], kind: 'approve' | 'choose' = 'approve'): WaitVerdict => ({
  waiting: true, certainty: 'sure', kind, question: '要不要提示他重新登一次?', by, rule: `${by}:x`, since: '2026-09-26T04:39:00.000Z',
})

describe('★③ 按内容判的「在等你」只挂 ask,不动运行状态', () => {
  it('★做完了 + 内容上在问他 → 还是 done(蓝点),但 ask 挂着(「等你」那一堆照旧数得到)', () => {
    const sessions = [view({ session_id: 'd4ac442e', status: 'done' })]
    const out = overlayWaiting(sessions, new Map([['claude:d4ac442e', verdict('rules')]]), new Map(), { nowSec: Math.floor(NOW_MS / 1000) })
    expect(out[0]?.status).toBe('done')
    expect(out[0]?.unread).toBe(true)
    expect(out[0]?.ask).toBeDefined()
    expect(out[0]?.wait_reason).toBeUndefined()
  })

  it('问过模型才拿准的(by: model)同样不动运行状态', () => {
    const out = overlayWaiting([view({ session_id: 'x', status: 'done' })], new Map([['claude:x', verdict('model')]]), new Map(), { nowSec: Math.floor(NOW_MS / 1000) })
    expect(out[0]?.status).toBe('done')
    expect(out[0]?.ask).toBeDefined()
  })

  it('★形式上真卡住的(by: form —— 权限弹窗 / 提问弹窗 / 等他批计划)照旧改成 waiting', () => {
    const out = overlayWaiting([view({ session_id: 'y', status: 'running' })], new Map([['claude:y', verdict('form')]]), new Map(), { nowSec: Math.floor(NOW_MS / 1000) })
    expect(out[0]?.status).toBe('waiting')
    expect(out[0]?.wait_reason).toBe('approval')
    expect(out[0]?.ask).toBeDefined()
  })

  it('在跑 + 内容上像在问他 → 还是在跑(它还在动,别把它从白点挪走)', () => {
    const out = overlayWaiting([view({ session_id: 'z', status: 'running' })], new Map([['claude:z', verdict('rules')]]), new Map(), { nowSec: Math.floor(NOW_MS / 1000) })
    expect(out[0]?.status).toBe('running')
    expect(out[0]?.ask).toBeDefined()
  })
})
